#!/usr/bin/env python3
"""Build a broad US-equity universe from the NASDAQ Trader symbol directory.

The directory publishes two pipe-delimited snapshots: NASDAQ-listed issues and
other exchange-listed issues (NYSE, NYSE American, NYSE Arca, and others). We
keep common stock and depositary-share lines, drop ETFs, test issues, warrants,
rights, units, preferreds, notes, and funds, then normalise class-share symbols
to the dash form used by Yahoo Finance (BRK.B -> BRK-B).

Usage:
    python scripts/build_universe.py
    python scripts/build_universe.py --source-dir /tmp/opencode --output config/universe.yaml
    python scripts/build_universe.py --offline --source-dir /tmp/opencode
"""

from __future__ import annotations

import argparse
import io
import re
import urllib.request
from pathlib import Path

import pandas as pd

NASDAQ_URL = "https://www.nasdaqtrader.com/dynamic/SymDir/nasdaqlisted.txt"
OTHER_URL = "https://www.nasdaqtrader.com/dynamic/SymDir/otherlisted.txt"

EXCLUDED_NAME = re.compile(
    r"warrant|right|unit|preferred|preference|depositary share|note|bond|"
    r"debenture|fund|trust|etf|\betn\b|closed[- ]end|series [a-z]|%",
    re.IGNORECASE,
)
VALID_SYMBOL = re.compile(r"^[A-Z][A-Z0-9-]{0,6}$")


def _download(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "FinHound universe builder/1.0"})
    with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310 - fixed NASDAQ URLs
        return response.read().decode("utf-8", errors="replace")


def _read_source(url: str, filename: str, source_dir: Path | None, offline: bool) -> pd.DataFrame:
    local = source_dir / filename if source_dir else None
    if local and local.exists():
        text = local.read_text()
    elif offline:
        raise SystemExit(f"error: {filename} is not present in {source_dir or 'the current directory'}")
    else:
        text = _download(url)
    return pd.read_csv(io.StringIO(text), sep="|", dtype=str)


def _normalise_symbol(raw: str) -> str | None:
    symbol = str(raw).strip().upper().replace(".", "-")
    if not VALID_SYMBOL.fullmatch(symbol):
        return None
    return symbol


def _common_equities(frame: pd.DataFrame, symbol_column: str, name_column: str) -> list[tuple[str, str]]:
    selected = frame[
        (frame.get("Test Issue", "N").fillna("N") == "N")
        & (frame.get("ETF", "N").fillna("N") == "N")
        & (~frame[name_column].fillna("").str.contains(EXCLUDED_NAME))
    ]
    rows: list[tuple[str, str]] = []
    for _, row in selected.iterrows():
        symbol = _normalise_symbol(row[symbol_column])
        if symbol is None:
            continue
        rows.append((symbol, str(row[name_column]).strip()))
    return rows


def build(source_dir: Path | None = None, offline: bool = False) -> list[tuple[str, str]]:
    nasdaq = _read_source(NASDAQ_URL, "nasdaqlisted.txt", source_dir, offline)
    other = _read_source(OTHER_URL, "otherlisted.txt", source_dir, offline)
    rows = _common_equities(nasdaq, "Symbol", "Security Name")
    rows += _common_equities(other, "ACT Symbol", "Security Name")
    by_symbol = {symbol: name for symbol, name in rows}
    ordered = sorted(by_symbol.items())
    if "SPY" not in by_symbol:
        ordered = [("SPY", "SPDR S&P 500 ETF Trust")] + ordered
    return ordered


def write_universe(path: Path, entries: list[tuple[str, str]], start_date: str) -> None:
    lines = [
        "# Generated by scripts/build_universe.py from the NASDAQ Trader symbol directory.",
        "# Refresh with: make universe",
        f'start_date: "{start_date}"',
        "symbols:",
    ]
    for symbol, _name in entries:
        tradable = "false" if symbol == "SPY" else "true"
        sector = "ETF" if symbol == "SPY" else "Unknown"
        # Quote the symbol: YAML 1.1 parses bare TRUE/ON/NO/OFF/Y/N as booleans,
        # which silently corrupts valid tickers such as TRUE.
        lines.append(f'  - {{symbol: "{symbol}", sector: "{sector}", tradable: {tradable}}}')
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("config/universe.yaml"))
    parser.add_argument("--source-dir", type=Path, default=None, help="Directory containing downloaded NASDAQ files")
    parser.add_argument("--offline", action="store_true", help="Read only local NASDAQ files; never download")
    parser.add_argument("--start-date", default="2015-01-01")
    parser.add_argument("--min-symbols", type=int, default=5000)
    args = parser.parse_args()

    entries = build(args.source_dir, args.offline)
    tradable = sum(1 for symbol, _ in entries if symbol != "SPY")
    if tradable < args.min_symbols:
        raise SystemExit(f"error: only {tradable} tradable symbols found; expected at least {args.min_symbols}")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    write_universe(args.output, entries, args.start_date)
    print(f"wrote {len(entries)} symbols ({tradable} tradable plus SPY) to {args.output}")


if __name__ == "__main__":
    main()
